import { BadRequestException, ForbiddenException, Injectable, NotFoundException } from '@nestjs/common';

import { PrismaService } from '../../shared/datasource/prisma/prisma.service';
import { ChatMessageDto } from './dto';

/**
 * History window for the model, by approximate token budget (newest first,
 * ~4 chars per token) rather than a fixed message count.
 */
const CONTEXT_TOKEN_BUDGET = 3000;
const MAX_CONTEXT_MESSAGES = 40;
const estimateTokens = (text: string) => Math.ceil((text?.length ?? 0) / 4);

/** Signed-in users own chats by userId; guests by deviceId. */
export interface CallerIdentity {
  userId?: number | null;
  deviceId?: string | null;
}

export interface TurnContext {
  /** Recent messages, oldest first, within the token budget. */
  history: ChatMessageDto[];
  /** Up to the last two user messages (for follow-ups like "y en Cartago?"). */
  earlierUserMessages: string[];
  /** providers_json of the latest reply that showed supplier cards. */
  lastSuppliersJson: string | null;
}

export interface AssistantReplyInput {
  content: string;
  model: string;
  providersJson?: string | null;
}

/**
 * Persistence for the AI chat. Turns are generated by
 * `assistant/ChatTurnService` and written here in one transaction.
 */
@Injectable()
export class ConversationService {
  constructor(private readonly prisma: PrismaService) {}

  async listConversations(caller: CallerIdentity) {
    return this.prisma.aiConversation.findMany({
      where: this.ownerWhere(caller),
      orderBy: { updatedAt: 'desc' },
      select: {
        conversationId: true,
        title: true,
        userId: true,
        deviceId: true,
        createdAt: true,
        updatedAt: true,
        messages: {
          orderBy: { createdAt: 'desc' },
          take: 1,
          select: { messageId: true, conversationId: true, content: true, role: true, createdAt: true },
        },
      },
    });
  }

  async getConversation(conversationId: string, caller: CallerIdentity) {
    await this.assertOwnership(conversationId, caller);
    return this.prisma.aiConversation.findUnique({
      where: { conversationId },
      include: { messages: { orderBy: { createdAt: 'asc' } } },
    });
  }

  async deleteConversation(conversationId: string, caller: CallerIdentity) {
    await this.assertOwnership(conversationId, caller);
    await this.prisma.aiConversation.delete({ where: { conversationId } });
  }

  async getMessages(conversationId: string, caller: CallerIdentity) {
    await this.assertOwnership(conversationId, caller);
    return this.prisma.aiMessage.findMany({ where: { conversationId }, orderBy: { createdAt: 'asc' } });
  }

  /** Everything a new turn needs from an existing conversation. */
  async turnContext(conversationId: string, caller: CallerIdentity): Promise<TurnContext> {
    await this.assertOwnership(conversationId, caller);
    const recent = await this.prisma.aiMessage.findMany({
      where: { conversationId },
      orderBy: { createdAt: 'desc' },
      take: MAX_CONTEXT_MESSAGES,
      select: { role: true, content: true, providersJson: true },
    });

    const history: ChatMessageDto[] = [];
    let remaining = CONTEXT_TOKEN_BUDGET;
    for (const m of recent) {
      const cost = estimateTokens(m.content);
      if (history.length > 0 && cost > remaining) break;
      history.push({ role: m.role as 'user' | 'assistant', content: m.content });
      remaining -= cost;
    }
    history.reverse();

    return {
      history,
      earlierUserMessages: recent
        .filter((m) => m.role === 'user')
        .slice(0, 2)
        .map((m) => m.content)
        .reverse(),
      lastSuppliersJson: recent.find((m) => m.role === 'assistant' && m.providersJson)?.providersJson ?? null,
    };
  }

  /**
   * Write a finished turn: the user message and the assistant replies,
   * creating the conversation when it's the first turn. Called only after
   * the model answered, so a turn the user stopped leaves nothing behind.
   */
  async persistTurn(
    caller: CallerIdentity,
    conversationId: string | null,
    userMessage: string,
    replies: AssistantReplyInput[],
  ) {
    const userId = caller.userId ?? null;
    const deviceId = caller.deviceId ?? '';
    if (!userId && !deviceId) {
      throw new BadRequestException('Either an authenticated user or a deviceId is required');
    }

    return this.prisma.$transaction(async (tx) => {
      const conv = conversationId
        ? await tx.aiConversation.update({ where: { conversationId }, data: { updatedAt: new Date() } })
        : await tx.aiConversation.create({
            data: {
              userId,
              deviceId,
              title: userMessage.length > 60 ? `${userMessage.slice(0, 57)}…` : userMessage,
            },
          });

      await tx.aiMessage.create({ data: { conversationId: conv.conversationId, role: 'user', content: userMessage } });
      const saved = [];
      for (const r of replies) {
        saved.push(
          await tx.aiMessage.create({
            data: {
              conversationId: conv.conversationId,
              role: 'assistant',
              content: r.content,
              model: r.model,
              providersJson: r.providersJson ?? null,
            },
          }),
        );
      }
      return { conversation: conv, replies: saved };
    });
  }

  /** After sign-in: claim this device's guest chats. Returns how many. */
  async mergeGuestConversations(userId: number, deviceId: string) {
    if (!userId || !deviceId) return 0;
    const result = await this.prisma.aiConversation.updateMany({
      where: { deviceId, userId: null },
      data: { userId },
    });
    return result.count;
  }

  /** Signed-in users see their chats from any device; guests only this device's. */
  private ownerWhere(caller: CallerIdentity) {
    if (caller.userId != null) return { userId: caller.userId };
    if (caller.deviceId) return { deviceId: caller.deviceId, userId: null };
    throw new BadRequestException('Either an authenticated user or a deviceId is required');
  }

  async assertOwnership(conversationId: string, caller: CallerIdentity) {
    const conv = await this.prisma.aiConversation.findUnique({ where: { conversationId } });
    if (!conv) throw new NotFoundException('Conversation not found');
    const ok =
      caller.userId != null
        ? conv.userId === caller.userId
        : !!caller.deviceId && conv.deviceId === caller.deviceId && conv.userId == null;
    if (!ok) throw new ForbiddenException('Access denied');
    return conv;
  }
}
